String _pick(Map<String, Map<String, String>> table, String ru) {
  final lang = LocaleService.current.value;
  if (lang == 'ru') return ru;
  return table[lang]?[ru] ?? table['en']?[ru] ?? ru;
}

String partLabel(String ru) => _pick(_parts, ru);

String schemaTitle(String ru) => _pick(_titles, ru);
